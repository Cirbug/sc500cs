"""Generate compact MCU character IDs from the same manifest as the RTL font."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
m = json.loads((root/'assets/menu_font/manifest.json').read_text(encoding='utf8'))
lines = ['/* Generated by tools/generate_mcu_menu_map.py; ID 0 is blank. */',
         '#ifndef MCU_MENU_MAP_H', '#define MCU_MENU_MAP_H']
pool=[0]; offsets={'':0}
for groups in (m['labels'],m['panel_labels']):
    for group in groups:
        for label in group:
            if label not in offsets:
                offsets[label]=len(pool)
                pool += [m['glyph_ids'][c] for c in label]+[0]
assert len(pool)<=256
lines.append('static const unsigned char mcu_label_pool[] = {'+','.join(map(str,pool))+'};')
lines.append('static const unsigned char mcu_labels[4][9] = {')
for group in m['labels']:
    lines.append('{'+','.join(str(offsets[s]) for s in group)+'},')
lines.append('};')
for name, group, cols in [('panel_values', m['panel_values'], 4),
                          ('effects',      m['effects'],      4),
                          ('values',       m['values'],       4)]:
    # 行数按列表实际长度走：panel_values 会因为新增模式名变长，
    # 写死 8 会变成"初始化项过多"，C 编译直接报错。
    lines.append(f'static const unsigned char mcu_{name}[1][{len(group)}][{cols}] = {{')
    lines.append('{')
    for s in group:
        lines.append('{' + ','.join(str(m['glyph_ids'][c]) for c in s) + '},')
    lines.append('},')
    lines.append('};')
assert all(len(s)<=8 for groups in (m['labels'],m['panel_labels']) for group in groups for s in group)
for page,group in enumerate(m['panel_labels']):
    if page in (1,5):continue # Reuse existing picture/record labels, without padding every page to nine rows.
    lines.append(f'static const unsigned char mcu_panel_labels_{page}[{len(group)}] = {{')
    for s in group:lines.append(str(offsets[s])+',')
    lines.append('};')
lines += ['static const unsigned char *const mcu_panel_labels[7] = {',
          'mcu_panel_labels_0,mcu_labels[1],mcu_panel_labels_2,mcu_panel_labels_3,',
          'mcu_panel_labels_4,mcu_labels[2],mcu_panel_labels_6};']
lines += ['#endif', '']
(root/'FDwork/shared/mcu_menu_map.h').write_text('\n'.join(lines),encoding='ascii')
