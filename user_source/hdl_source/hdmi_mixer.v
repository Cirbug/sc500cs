    input wire [6:0]  I_track_area,
    // 三色（红/绿/蓝）各自的确认框，bit0/1/2 对应 cvalid
    input wire [2:0]  I_color3_valid,
    input wire [11:0] I_c3r_x0, I_c3r_y0, I_c3r_x1, I_c3r_y1,
    input wire [11:0] I_c3g_x0, I_c3g_y0, I_c3g_x1, I_c3g_y1,
    input wire [11:0] I_c3b_x0, I_c3b_y0, I_c3b_x1, I_c3b_y1,
    input wire [1:0]  I_target_color,   // 0=红 1=绿 2=蓝（选中目标的框颜色）
    /* 2026-10-27 第四期：1 = 颜色识别档（image_step==0），透传给 image9 的追踪 OSD，
     * 让它只画红/绿/蓝三个连通域框。 */
    input wire        I_color_show,

    output wire       O_video_rd_en,
    input wire [23:0] I_video_rd_data,
    output wire       O_hdmi_vsync,
    output wire       O_hdmi_hsync,
    output wire       O_hdmi_de,
    output wire [23:0] O_hdmi_data,
    // Expose the pre-effect video and the opaque OSD mask so the _9 Sobel
    // stage can process only camera pixels and then restore OSD colors.
    output wire [23:0] O_base_data,
    output wire        O_overlay_valid
);

    hdmi_mixer_image9 #(
        .H_OFFSET   (H_OFFSET),
        .V_OFFSET   (V_OFFSET),
        .IMG_WIDTH  (IMG_WIDTH),
        .IMG_HEIGHT (IMG_HEIGHT),
        .DEBUG_MODE (DEBUG_MODE),
        .SPRITE_ENABLE(SPRITE_ENABLE),
        .SHAPE_LABEL_ENABLE(SHAPE_LABEL_ENABLE)
    ) u_image9 (
        .I_clk           (I_clk),
        .I_rst_n         (I_rst_n),
