"""Generate the fixed 32x32 monochrome menu subset from an OFL Noto font.

Usage: python tools/generate_menu_font.py --font path/to/NotoSansSC-Bold.otf
Pillow is required. The generated RTL embeds the ROM initialization so FPGA
builds do not depend on font installation or the working directory.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
LABELS = [
    ["菜单", "曝光", "增益", "图像设置", "录制设置", "显示模式", "图像特效", "标志", "帧长"],
    ["图像设置", "黑电平", "伽马", "数字亮度", "饱和度", "白平衡", "降噪", "恢复默认"],
    ["录制设置", "单张拍照", "开始录制", "停止录制", "保存间隔", "已保存", "状态", "返回"],
    ["显示模式", "普通画面", "图形识别", "运动检测", "红色目标跟踪", "", "", ""],
]
VALUES = ["返回", "关闭", "开启", "自动", "平滑", "近灰", "低", "中", "高", "恢复", "空闲", "写入", "错误", "录制"]
EFFECTS = ["", "灰度", "反色", "二值化", "复古色", "边缘检测"]
SHAPES = ["", "矩形", "梯形", "圆形", "三角形", "菱形"]
PANEL_LABELS = [
    ["相机设置", "图像调整", "曝光控制", "显示模式", "目标追踪", "拍照录制", "系统信息"],
    LABELS[1],
    ["曝光控制", "曝光", "增益", "帧长"],
    ["显示模式", "普通画面", "图形识别", "运动检测", "红色目标跟踪", "图像特效"],
    ["目标追踪", "红色目标跟踪", "重新识别", "自动对焦"],
    LABELS[2],
    ["系统信息", "标志", "统计信息"],
]
PANEL_VALUES = ["手动", "普通", "识别", "运动", "跟踪", "返回", "关闭", "开启"]


def generate(font_path, extend_existing=False):
    font = ImageFont.truetype(str(font_path), 28)
    try: font.set_variation_by_name('Bold')
    except (OSError,ValueError): pass
    prior=None
    if extend_existing:
        prior=json.loads((ROOT/'assets/menu_font/manifest.json').read_text(encoding='utf8'))
    chars = list(dict.fromkeys("".join(sum(LABELS, []) + VALUES + EFFECTS + SHAPES +
                                     sum(PANEL_LABELS, []) + PANEL_VALUES)))
    old_chars=list(prior['glyph_ids']) if prior else []
    if prior: chars=old_chars+[ch for ch in chars if ch not in old_chars]
    old_words=[int(v,16) for v in (ROOT/'assets/menu_font/rows.hex').read_text().split()] if prior else []
    assert len(chars) < 128
    ids = {c: i + 1 for i, c in enumerate(chars)}
    images = [Image.new("1", (32, 32))]
    for c in chars:
        if c in old_chars:
            im=Image.new('1',(32,32))
            for y in range(32):
                for x in range(32): im.putpixel((x,y),bool(old_words[ids[c]*32+y] & (1<<(31-x))))
            images.append(im);continue
        im = Image.new("L", (32, 32))
        box = font.getbbox(c)
        assert box[2] - box[0] <= 32 and box[3] - box[1] <= 32
        ImageDraw.Draw(im).text(((32 - (box[2] - box[0])) // 2 - box[0],
                                (32 - (box[3] - box[1])) // 2 - box[1]), c, font=font, fill=255)
        images.append(im.point(lambda p: 255 if p >= 128 else 0, mode="1"))
        assert images[-1].getbbox(), f"Empty glyph: {c}"
    assert len({im.tobytes() for im in images}) == len(images), "Missing/duplicate glyphs"
    hdl = ROOT / "user_source/hdl_source"
    lines = ["// Generated by tools/generate_menu_font.py; do not edit.",
             "// Noto Sans SC subset; see assets/menu_font/OFL.txt.",
             "`ifndef UI_FONT_CN_V", "`define UI_FONT_CN_V",
             "module ui_font_cn(input wire clk, input wire [11:0] address,",
             "                  output reg [31:0] row_bits);",
             "    reg [31:0] rom[0:4095]; // synchronous read infers ROM in TD",
             "    initial begin"]
    words = []
    for i in range(128):
        for y in range(32):
            bits = 0
            for x in range(32):
                bits = (bits << 1) | int(i < len(images) and bool(images[i].getpixel((x, y))))
            words.append(bits)
            lines.append(f"        rom[{i*32+y}] = 32'h{bits:08x};")
    lines += ["    end", "    always @(posedge clk) row_bits <= rom[address];",
              "endmodule", "`endif", ""]
    (hdl / "ui_font_cn.v").write_text("\n".join(lines), encoding="ascii")
    mapping = ["// Generated menu glyph IDs; zero is a transparent space.",
               "function [6:0] cn_label_id;", "    input [1:0] page; input [3:0] line_id; input [2:0] cell_id;",
               "    begin", "        cn_label_id=0;", "        case({page,line_id,cell_id})"]
    for page, labels in enumerate(LABELS):
        for line, label in enumerate(labels):
            for cell, c in enumerate(label):
                key = (page << 7) | (line << 3) | cell
                mapping.append(f"            9'd{key}: cn_label_id=7'd{ids[c]};")
    mapping += ["        endcase", "    end", "endfunction",
                "function [6:0] cn_value_id;", "    input [3:0] kind; input [1:0] cell_id;",
                "    begin", "        cn_value_id=0;", "        case({kind,cell_id})"]
    for kind, label in enumerate(VALUES):
        for cell, c in enumerate(label):
            mapping.append(f"            6'd{kind*4+cell}: cn_value_id=7'd{ids[c]};")
    mapping += ["        endcase", "    end", "endfunction", ""]
    for name, labels in [('cn_effect_id', EFFECTS), ('cn_shape_id', SHAPES)]:
        mapping += [f"function [6:0] {name};",
                    "    input [2:0] kind; input [1:0] cell_id;",
                    "    begin", f"        {name}=0;", "        case({kind,cell_id})"]
        for kind, label in enumerate(labels):
            for cell, c in enumerate(label):
                mapping.append(f"            5'd{kind*4+cell}: {name}=7'd{ids[c]};")
        mapping += ["        endcase", "    end", "endfunction", ""]
    (hdl / "ui_font_cn_map.vh").write_text("\n".join(mapping), encoding="ascii")
    out = ROOT / "assets/menu_font"
    out.mkdir(parents=True, exist_ok=True)
    (out / "manifest.json").write_text(json.dumps({
        "preserved_previous_glyphs": len(old_chars),
        "previous_font_sha256": prior.get("font_sha256") if prior else None,
        "font": font.getname(), "font_sha256": hashlib.sha256(font_path.read_bytes()).hexdigest(),
        "size": 32, "raster_size": 28, "threshold": 128,
        "layout": "32 rows per glyph, bit31 leftmost, ID0 blank",
        "labels": LABELS, "values": VALUES, "effects": EFFECTS, "shapes": SHAPES, "glyph_ids": ids,
        "panel_labels": PANEL_LABELS, "panel_values": PANEL_VALUES,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "rows.hex").write_text("".join(f"{w:08x}\n" for w in words), encoding="ascii")
    (out / "labels.hex").write_text("".join(
        f"{ids[label[cell]] if cell < len(label) else 0:02x}\n"
        for labels in LABELS for label in (labels+[""]*(16-len(labels))) for cell in range(8)), encoding="ascii")
    (out / "values.hex").write_text("".join(
        f"{ids[label[cell]] if cell < len(label) else 0:02x}\n"
        for label in VALUES for cell in range(4)), encoding="ascii")
    for name, labels in [('effects', EFFECTS), ('shapes', SHAPES)]:
        (out / (name+'.hex')).write_text(''.join(
            f'{ids[label[cell]] if cell < len(label) else 0:02x}\n'
            for label in labels+['']*(8-len(labels)) for cell in range(4)), encoding='ascii')
    sheet = Image.new("RGB", (8*64, ((len(images)+7)//8)*64), "#101820")
    for i, im in enumerate(images):
        sheet.paste("white", ((i%8)*64+16, (i//8)*64+16), im)
    sheet.save(out / "glyphs.png")
    print(f"Generated {len(chars)} glyphs, ROM 4096x32 (16384 bytes)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--extend-existing",action="store_true")
    args=parser.parse_args()
    generate(args.font,args.extend_existing)
